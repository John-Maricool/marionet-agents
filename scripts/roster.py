"""Generate ROSTER.md (the agent roster) from the agent files. Run after adding or changing agents."""
from __future__ import annotations

import re
import sys

from library import ROOT, load_library, load_yaml

TIER = {0: "read-only", 1: "drafts", 2: "internal changes", 3: "needs approval", 4: "human only"}


def summary(desc: str) -> str:
    text = " ".join(desc.split())
    text = text.split(" Not for:")[0]
    parts = re.split(r"(?<=\.)\s", text, maxsplit=2)
    first = parts[0]
    if len(first) < 40 and len(parts) > 1:
        first = f"{first} {parts[1]}"
    return first.replace("|", "/")


def main() -> int:
    lib = load_library()
    by_team: dict[str, list] = {}
    for a in lib.agents:
        by_team.setdefault(a.team_dir, []).append(a)

    order = ["leadership"] + sorted(t for t in by_team if t != "leadership")
    total_tasks = 0
    lines = [
        "# Agent roster",
        "",
        "Generated by `scripts/roster.py` from `agents/`. Do not edit by hand.",
        "",
    ]
    body: list[str] = []
    for team in order:
        agents = by_team[team]
        lead = lib.teams[team]["lead"]
        agents.sort(key=lambda a: (a.name != lead, a.name))
        body += [f"## {team} ({len(agents)})", "", "| Agent | Does | Model | Approval | Status | Tests |", "| --- | --- | --- | --- | --- | --- |"]
        for a in agents:
            n = len(load_yaml(a.evals_path).get("tasks") or [])
            total_tasks += n
            star = " (lead)" if a.name == lead else ""
            path = a.path.relative_to(ROOT).as_posix()
            tier = a.meta["approval_tier"]
            body.append(
                f"| [{a.name}]({path}){star} | {summary(a.meta['description'])} | "
                f"{a.meta['model']} | {tier} {TIER[tier]} | {a.meta['status']} | {n} |"
            )
        body.append("")
    verified = sum(a.meta["status"] == "verified" for a in lib.agents)
    lines += [
        f"**{len(lib.agents)} agents** in **{len(by_team)} teams**, **{len(lib.skills)} skills**, "
        f"**{total_tasks} eval tasks**. Verified: {verified} of {len(lib.agents)}.",
        "",
        "Requests enter through `chief-of-staff`, which routes to team leads; leads route to their specialists.",
        "",
    ] + body
    (ROOT / "ROSTER.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote ROSTER.md: {len(lib.agents)} agents, {total_tasks} eval tasks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
