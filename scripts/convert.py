"""Generate tool-specific agent and skill files into dist/<target>/.

All tool-specific knowledge lives here and in capabilities.yaml.
Targets marked VERIFY have file formats that must be checked against current vendor docs.
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

import yaml

from library import ROOT, Agent, Library, load_library

DIST = ROOT / "dist"
HEADER = "Generated by scripts/convert.py from agents/. Do not edit by hand."


def one_line(text: str) -> str:
    return " ".join(str(text).split())


def tools_for(lib: Library, agent: Agent, target: str, warn) -> list[str]:
    tools: list[str] = []
    for cap in agent.meta.get("capabilities") or []:
        mapped = lib.capabilities.get(cap, {}).get(target)
        if mapped is None:
            warn(f"{target}: {agent.name}: no equivalent for capability '{cap}', left out")
            continue
        tools.extend(t for t in mapped if t not in tools)
    return tools


def md_with_frontmatter(meta: dict, body: str) -> str:
    fm = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=10_000).strip()
    return f"---\n{fm}\n---\n<!-- {HEADER} -->\n\n{body.lstrip()}"


def copy_skills(lib: Library, dest: Path) -> None:
    for folder, (_, _, src) in lib.skills.items():
        shutil.copytree(src, dest / folder, dirs_exist_ok=True)


# ---------- targets ----------

def build_claude_code(lib: Library, out: Path, warn) -> None:
    model_map = lib.models.get("tool_models", {}).get("claude-code", {})
    for a in lib.agents:
        meta = {"name": a.name, "description": one_line(a.meta["description"])}
        tools = tools_for(lib, a, "claude-code", warn)
        if tools:
            meta["tools"] = ", ".join(tools)
        meta["model"] = model_map.get(a.meta.get("model"), "inherit")
        path = out / ".claude" / "agents" / f"{a.name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(md_with_frontmatter(meta, a.body), encoding="utf-8")
    copy_skills(lib, out / ".claude" / "skills")


def build_cursor(lib: Library, out: Path, warn) -> None:
    # VERIFY: Cursor subagent location and fields.
    for a in lib.agents:
        meta = {"name": a.name, "description": one_line(a.meta["description"])}
        path = out / ".cursor" / "agents" / f"{a.name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(md_with_frontmatter(meta, a.body), encoding="utf-8")
    copy_skills(lib, out / ".agents" / "skills")


def build_gemini_cli(lib: Library, out: Path, warn) -> None:
    # VERIFY: Gemini CLI subagent location and fields.
    for a in lib.agents:
        meta = {"name": a.name, "description": one_line(a.meta["description"])}
        tools = tools_for(lib, a, "gemini-cli", warn)
        if tools:
            meta["tools"] = tools
        path = out / ".gemini" / "agents" / f"{a.name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(md_with_frontmatter(meta, a.body), encoding="utf-8")
    copy_skills(lib, out / ".agents" / "skills")


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_codex(lib: Library, out: Path, warn) -> None:
    # VERIFY: Codex agent TOML field names are unconfirmed.
    for a in lib.agents:
        body = a.body.strip()
        if "'''" in body:
            warn(f"codex: {a.name}: body contains ''' and cannot be a TOML literal string; skipped")
            continue
        text = (
            f"# {HEADER}\n"
            f"name = {toml_str(a.name)}\n"
            f"description = {toml_str(one_line(a.meta['description']))}\n"
            f"developer_instructions = '''\n{body}\n'''\n"
        )
        path = out / ".codex" / "agents" / f"{a.name}.toml"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    copy_skills(lib, out / ".agents" / "skills")


def build_prompts(lib: Library, out: Path, warn) -> None:
    """One self-contained system prompt per agent, with its skills inlined.

    Paste into ChatGPT (custom GPT or project instructions), Claude.ai (project instructions),
    Gemini (Gem instructions), or send as the system message to any LLM API.
    """
    for a in lib.agents:
        parts = [
            f"<!-- {HEADER} -->",
            f"# {a.name}",
            "",
            f"> {one_line(a.meta['description'])}",
            "",
            a.body.strip(),
        ]
        for s in a.meta.get("skills") or []:
            _, skill_body, _ = lib.skills[s]
            parts += ["", "---", "", f"<!-- skill: {s} -->", skill_body.strip()]
        path = out / a.team_dir / f"{a.name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(parts) + "\n", encoding="utf-8")


TARGETS = {
    "claude-code": build_claude_code,
    "cursor": build_cursor,
    "gemini-cli": build_gemini_cli,
    "codex": build_codex,
    "prompts": build_prompts,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("targets", nargs="*", help=f"any of {', '.join(TARGETS)} (default: all)")
    args = parser.parse_args()
    targets = args.targets or list(TARGETS)
    unknown = [t for t in targets if t not in TARGETS]
    if unknown:
        parser.error(f"unknown target(s): {', '.join(unknown)}")

    lib = load_library()
    if lib.load_errors:
        print("Run scripts/lint.py first; these files could not be read:")
        print("\n".join(lib.load_errors))
        return 1

    warnings: list[str] = []
    for target in targets:
        out = DIST / target
        shutil.rmtree(out, ignore_errors=True)
        TARGETS[target](lib, out, warnings.append)
        print(f"built {target}: {len(lib.agents)} agents, {len(lib.skills)} skills -> {out.relative_to(ROOT)}")
    for w in warnings:
        print(f"warning: {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
